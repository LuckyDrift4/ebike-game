"""
Build the RideKit packages from roblox/RideKit/*.lua and the Blender animation.

  python roblox/build_ridekit.py

Writes:
  roblox/RideKit/AnimData.lua   R6 riding clips exported from blender/anim/ride_anims.blend
                                (roblox/anim/ride_anims.json), as a ModuleScript
  roblox/RideKit_Server.lua     paste into a Script inside the bike model
  roblox/RideKit_Client.lua     paste into a LocalScript in StarterPlayerScripts
  roblox/RideKit.rbxmx          the same as a Folder for Insert from File:
                                  Config, Rig, Physics, AnimPlayer, AnimData -> ModuleScripts
                                  BikeServer -> Script (RunContext Server)
                                  BikeClient -> Script (RunContext Client)
  roblox/RideAnims_R6.rbxmx     the Blender clips as KeyframeSequences for the Animation Editor
  roblox/tests/bike_ref.luau    test copy of blender/anim/bike_ref.json
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(HERE, "RideKit")
OUT = os.path.join(HERE, "RideKit.rbxmx")
ANIM_JSON = os.path.join(HERE, "anim", "ride_anims.json")

ITEMS = [
    ("ModuleScript", "Config", "Config.lua", None),
    ("ModuleScript", "Rig", "Rig.lua", None),
    ("ModuleScript", "Physics", "Physics.lua", None),
    ("ModuleScript", "AnimPlayer", "AnimPlayer.lua", None),
    ("ModuleScript", "AnimData", "AnimData.lua", None),
    ("Script", "BikeServer", "BikeServer.server.lua", 1),   # Enum.RunContext.Server
    ("Script", "BikeClient", "BikeClient.client.lua", 2),   # Enum.RunContext.Client
]
PART_ORDER = ["Torso", "Head", "Right Arm", "Left Arm", "Right Leg", "Left Leg"]
XML_HEAD = ('<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" '
            'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
            'xsi:noNamespaceSchemaLocation="http://www.roblox.com/roblox.xsd" version="4">\n')


def item(cls, name, source, ref, run_context):
    assert "]]>" not in source, f"{name}: source may not contain ]]>"
    props = [f'<string name="Name">{name}</string>',
             f'<ProtectedString name="Source"><![CDATA[{source}]]></ProtectedString>']
    if run_context is not None:
        props.append(f'<token name="RunContext">{run_context}</token>')
        props.append('<bool name="Disabled">false</bool>')
    return f'<Item class="{cls}" referent="RBX{ref}"><Properties>{"".join(props)}</Properties></Item>'


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


# --------------------------------------------------------------------------- #
#  Blender clips -> AnimData.lua and Animation Editor KeyframeSequences
# --------------------------------------------------------------------------- #
def anim_data_lua(data):
    lines = ["-- R6 riding clips keyframed in Blender (blender/anim/ride_anims.blend).",
             "-- Generated by roblox/build_ridekit.py from roblox/anim/ride_anims.json; do not edit.",
             "-- Each key: time (s) and every R6 joint's Motor6D.Transform rotation as a quaternion {x, y, z, w}.",
             "return {", f"\tbike = {lua_str(data['bike'])},", "\tclips = {"]
    for name, c in data["clips"].items():
        lines.append(f"\t\t{name} = {{ length = {c['length']}, loop = {str(c['loop']).lower()}, "
                     f"steer = {c['steer']}, keys = {{")
        for k in c["keys"]:
            pose = ", ".join(f"[{lua_str(p)}] = {{ {', '.join(f'{v:.5f}' for v in k['pose'][p])} }}" for p in PART_ORDER)
            lines.append(f"\t\t\t{{ t = {k['t']}, pose = {{ {pose} }} }},")
        lines.append("\t\t} },")
    lines += ["\t},", "}", ""]
    return "\n".join(lines)


def quat_to_rows(q):
    x, y, z, w = q
    return [1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w),
            2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w),
            2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]


def keyframe_sequences(data):
    """The Blender clips as KeyframeSequences (Pose CFrame = Motor6D.Transform)."""
    ref = [100]

    def nref():
        ref[0] += 1
        return f"RBX{ref[0]}"

    def cf_xml(rows):
        vals = "".join(f"<R{i}{k}>{rows[i * 3 + k]:.6f}</R{i}{k}>" for i in range(3) for k in range(3))
        return f'<CoordinateFrame name="CFrame"><X>0</X><Y>0</Y><Z>0</Z>{vals}</CoordinateFrame>'

    def pose(name, rows, children=""):
        return (f'<Item class="Pose" referent="{nref()}"><Properties><string name="Name">{name}</string>'
                f'{cf_xml(rows)}<float name="Weight">1</float>'
                f'<token name="EasingStyle">0</token><token name="EasingDirection">0</token>'
                f'</Properties>{children}</Item>')

    ident = [1, 0, 0, 0, 1, 0, 0, 0, 1]
    seqs = []
    for name, c in data["clips"].items():
        frames = []
        for k in c["keys"]:
            limbs = "".join(pose(p, quat_to_rows(k["pose"][p])) for p in PART_ORDER[1:])
            torso = pose("Torso", quat_to_rows(k["pose"]["Torso"]), limbs)
            frames.append(f'<Item class="Keyframe" referent="{nref()}"><Properties><string name="Name">Keyframe</string>'
                          f'<float name="Time">{k["t"]}</float></Properties>{pose("HumanoidRootPart", ident, torso)}</Item>')
        seqs.append(f'<Item class="KeyframeSequence" referent="{nref()}"><Properties>'
                    f'<string name="Name">Ride{name}</string><bool name="Loop">{str(c["loop"]).lower()}</bool>'
                    f'<token name="Priority">2</token></Properties>\n' + "\n".join(frames) + "\n</Item>")
    return (XML_HEAD + '<Item class="Folder" referent="RBX99"><Properties><string name="Name">RideAnims_R6</string>'
            '</Properties>\n' + "\n".join(seqs) + "\n</Item>\n</roblox>\n")


# --------------------------------------------------------------------------- #
#  paste-in single files
# --------------------------------------------------------------------------- #
def inline(name, fn):
    with open(os.path.join(SRC, fn), encoding="utf-8") as f:
        src = f.read().rstrip("\n")
    body = "\n".join(("\t" + l) if l.strip() else l for l in src.split("\n"))
    return f"local {name} = (function()\n{body}\nend)()\n"


def body_of(fn):
    with open(os.path.join(SRC, fn), encoding="utf-8") as f:
        src = f.read()
    b = src[src.index("-- @body"):]
    return b[:b.index("-- @end")] if "-- @end" in b else b


def single_files():
    """Copy-paste versions: one Script for the bike, one LocalScript for StarterPlayerScripts."""
    # NOTE: paste-in files must survive a copy that loses the start of the file:
    # they open with a long line of dashes (any tail of it is still a comment),
    # never with prose, and every service is looked up where it is used.
    guard = "-" * 160 + "\n\n"
    server = (
        guard
        + inline("Config", "Config.lua") + inline("Rig", "Rig.lua") + inline("Physics", "Physics.lua")
        + "\nlocal bike = script.Parent :: Model\n\n" + body_of("BikeServer.server.lua"))
    client = (
        guard
        + inline("Config", "Config.lua") + inline("Physics", "Physics.lua")
        + inline("AnimPlayer", "AnimPlayer.lua") + inline("AnimData", "AnimData.lua")
        + "\n" + body_of("BikeClient.client.lua")
        + "\nlocal CollectionService = game:GetService(\"CollectionService\")\n"
        + "for _, b in ipairs(CollectionService:GetTagged(\"RideKitBike\")) do\n\ttask.spawn(runBike, b)\nend\n"
        "CollectionService:GetInstanceAddedSignal(\"RideKitBike\"):Connect(function(b)\n\ttask.spawn(runBike, b)\nend)\n")
    for name, text in (("RideKit_Server.lua", server), ("RideKit_Client.lua", client)):
        with open(os.path.join(HERE, name), "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote", os.path.join(HERE, name))


def bike_ref_luau():
    with open(os.path.join(ROOT, "blender", "anim", "bike_ref.json"), encoding="utf-8") as f:
        ref = json.load(f)

    def val(v):
        if isinstance(v, dict):
            return "{ " + ", ".join(f"{k} = {val(x)}" for k, x in v.items()) + " }"
        if isinstance(v, list):
            return "{ " + ", ".join(val(x) for x in v) + " }"
        if isinstance(v, str):
            return lua_str(v)
        return repr(v)
    with open(os.path.join(HERE, "tests", "bike_ref.luau"), "w", encoding="utf-8") as f:
        f.write("-- Generated from blender/anim/bike_ref.json by build_ridekit.py\nreturn " + val(ref) + "\n")


def main():
    with open(ANIM_JSON, encoding="utf-8") as f:
        data = json.load(f)
    with open(os.path.join(SRC, "AnimData.lua"), "w", encoding="utf-8") as f:
        f.write(anim_data_lua(data))
    with open(os.path.join(HERE, "RideAnims_R6.rbxmx"), "w", encoding="utf-8") as f:
        f.write(keyframe_sequences(data))
    bike_ref_luau()
    single_files()
    parts = []
    for i, (cls, name, fn, rc) in enumerate(ITEMS, start=1):
        with open(os.path.join(SRC, fn), encoding="utf-8") as f:
            parts.append(item(cls, name, f.read(), i, rc))
    xml = (XML_HEAD + '<Item class="Folder" referent="RBX0"><Properties><string name="Name">RideKit</string></Properties>\n'
           + "\n".join(parts) + "\n</Item>\n</roblox>\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(xml)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
